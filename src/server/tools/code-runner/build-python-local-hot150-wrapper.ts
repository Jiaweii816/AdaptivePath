import type {
  ComparisonStrategy,
  ProblemExecutionContract,
} from "@/data/hot150/local-run-types";
import type { CodeRunTestCase } from "@/types/code-runner";
import { buildPythonUserCodeGuard } from "./build-python-wrapper";
import { PISTON_RESULT_MARKER } from "./normalize-run-result";

export function buildPythonLocalHot150Wrapper(args: {
  comparisonConfig?: Record<string, unknown>;
  comparisonStrategy: ComparisonStrategy;
  contract: ProblemExecutionContract;
  testCases: CodeRunTestCase[];
  userCode: string;
}) {
  return [
    "from __future__ import annotations",
    "from typing import *",
    "import collections as __pc_collections",
    "import contextlib as __pc_contextlib",
    "import copy as __pc_copy",
    "import io as __pc_io",
    "import json as __pc_json",
    "import math as __pc_math",
    "import traceback as __pc_traceback",
    "",
    buildLeetCodeHelperTypes(),
    "",
    `__pc_marker = ${JSON.stringify(PISTON_RESULT_MARKER)}`,
    `__pc_user_code_filename = "user_code.py"`,
    `__pc_user_code = ${JSON.stringify(args.userCode)}`,
    "",
    "def __pc_emit(payload):",
    "    print(__pc_marker + __pc_json.dumps(payload, ensure_ascii=False, separators=(',', ':')))",
    "",
    ...buildPythonUserCodeGuard(),
    "",
    "try:",
    "    __pc_compiled_user_code = compile(__pc_user_code, __pc_user_code_filename, 'exec')",
    "    exec(__pc_compiled_user_code, globals())",
    "except SyntaxError as exc:",
    "    __pc_error = __pc_format_error(exc)",
    "    __pc_emit({'status': 'syntax_error', 'testResults': [], 'error': __pc_error, 'errorLocation': __pc_syntax_error_location(exc)})",
    "    raise SystemExit(0)",
    "except Exception as exc:",
    "    __pc_error = __pc_format_error(exc)",
    "    __pc_emit({'status': 'runtime_error', 'testResults': [], 'error': __pc_error, 'errorLocation': __pc_traceback_error_location(exc)})",
    "    raise SystemExit(0)",
    "",
    `__pc_tests = __pc_json.loads(${JSON.stringify(JSON.stringify(args.testCases))})`,
    `__pc_contract = __pc_json.loads(${JSON.stringify(JSON.stringify(args.contract))})`,
    `__pc_comparison_strategy = ${JSON.stringify(args.comparisonStrategy)}`,
    `__pc_comparison_config = __pc_json.loads(${JSON.stringify(JSON.stringify(args.comparisonConfig ?? {}))})`,
    "",
    buildRuntimeHelpers(),
    "",
    "__pc_run()",
    "",
  ].join("\n");
}

function buildLeetCodeHelperTypes() {
  return [
    "class ListNode:",
    "    def __init__(self, val=0, next=None):",
    "        self.val = val",
    "        self.next = next",
    "",
    "class TreeNode:",
    "    def __init__(self, val=0, left=None, right=None):",
    "        self.val = val",
    "        self.left = left",
    "        self.right = right",
    "",
    "class Node:",
    "    def __init__(self, val=0, *args, **kwargs):",
    "        self.val = val",
    "        self.neighbors = []",
    "        self.next = None",
    "        self.random = None",
    "        self.children = []",
    "        self.left = None",
    "        self.right = None",
    "        self.isLeaf = False",
    "        self.topLeft = None",
    "        self.topRight = None",
    "        self.bottomLeft = None",
    "        self.bottomRight = None",
    "        if len(args) == 1:",
    "            if isinstance(args[0], bool):",
    "                self.isLeaf = bool(args[0])",
    "            else:",
    "                self.neighbors = args[0] if args[0] is not None else []",
    "        elif len(args) == 3:",
    "            self.left, self.right, self.next = args",
    "        elif len(args) >= 5:",
    "            self.isLeaf = bool(args[0])",
    "            self.topLeft, self.topRight, self.bottomLeft, self.bottomRight = args[1:5]",
    "        for key, value in kwargs.items():",
    "            setattr(self, key, value)",
  ].join("\n");
}

function buildRuntimeHelpers() {
  return [
    "def __pc_normalize_type(type_name):",
    "    return str(type_name or '').strip().lower().replace(' ', '')",
    "",
    "def __pc_list_to_linked(values):",
    "    if values is None:",
    "        return None",
    "    dummy = ListNode(0)",
    "    tail = dummy",
    "    for value in values:",
    "        tail.next = ListNode(value)",
    "        tail = tail.next",
    "    return dummy.next",
    "",
    "def __pc_linked_to_list(node):",
    "    values = []",
    "    seen = set()",
    "    while node is not None:",
    "        ident = id(node)",
    "        if ident in seen:",
    "            values.append('__cycle__')",
    "            break",
    "        seen.add(ident)",
    "        values.append(node.val)",
    "        node = node.next",
    "    return values",
    "",
    "def __pc_list_to_tree(values):",
    "    if not values:",
    "        return None",
    "    nodes = [None if value is None else TreeNode(value) for value in values]",
    "    child_index = 1",
    "    for node in nodes:",
    "        if node is None:",
    "            continue",
    "        if child_index < len(nodes):",
    "            node.left = nodes[child_index]",
    "            child_index += 1",
    "        if child_index < len(nodes):",
    "            node.right = nodes[child_index]",
    "            child_index += 1",
    "    return nodes[0]",
    "",
    "def __pc_tree_to_list(root):",
    "    if root is None:",
    "        return []",
    "    out = []",
    "    queue = __pc_collections.deque([root])",
    "    while queue:",
    "        node = queue.popleft()",
    "        if node is None:",
    "            out.append(None)",
    "            continue",
    "        out.append(node.val)",
    "        queue.append(node.left)",
    "        queue.append(node.right)",
    "    while out and out[-1] is None:",
    "        out.pop()",
    "    return out",
    "",
    "def __pc_list_to_node_tree(values):",
    "    if not values:",
    "        return None",
    "    nodes = [None if value is None else Node(value) for value in values]",
    "    child_index = 1",
    "    for node in nodes:",
    "        if node is None:",
    "            continue",
    "        if child_index < len(nodes):",
    "            node.left = nodes[child_index]",
    "            child_index += 1",
    "        if child_index < len(nodes):",
    "            node.right = nodes[child_index]",
    "            child_index += 1",
    "    return nodes[0]",
    "",
    "def __pc_node_next_to_list(root):",
    "    if root is None:",
    "        return []",
    "    out = []",
    "    level = root",
    "    while level:",
    "        cur = level",
    "        next_level = None",
    "        while cur:",
    "            out.append(cur.val)",
    "            if next_level is None:",
    "                next_level = getattr(cur, 'left', None) or getattr(cur, 'right', None)",
    "            cur = getattr(cur, 'next', None)",
    "        out.append('#')",
    "        level = next_level",
    "    return out",
    "",
    "def __pc_list_to_random_node(values):",
    "    if not values:",
    "        return None",
    "    nodes = [Node(item[0] if item else 0) for item in values]",
    "    for index, item in enumerate(values):",
    "        if index + 1 < len(nodes):",
    "            nodes[index].next = nodes[index + 1]",
    "        random_index = item[1] if item and len(item) > 1 else None",
    "        nodes[index].random = nodes[random_index] if isinstance(random_index, int) and 0 <= random_index < len(nodes) else None",
    "    return nodes[0]",
    "",
    "def __pc_random_node_to_list(head):",
    "    if head is None:",
    "        return []",
    "    nodes = []",
    "    index_by_id = {}",
    "    cur = head",
    "    while cur is not None and id(cur) not in index_by_id:",
    "        index_by_id[id(cur)] = len(nodes)",
    "        nodes.append(cur)",
    "        cur = getattr(cur, 'next', None)",
    "    out = []",
    "    for node in nodes:",
    "        random_node = getattr(node, 'random', None)",
    "        random_index = index_by_id.get(id(random_node)) if random_node is not None else None",
    "        out.append([node.val, random_index])",
    "    return out",
    "",
    "def __pc_list_to_graph(adjacency):",
    "    if not adjacency:",
    "        return None",
    "    nodes = [Node(index + 1) for index in range(len(adjacency))]",
    "    for index, neighbors in enumerate(adjacency):",
    "        nodes[index].neighbors = [nodes[value - 1] for value in neighbors]",
    "    return nodes[0]",
    "",
    "def __pc_graph_to_list(node):",
    "    if node is None:",
    "        return []",
    "    by_val = {}",
    "    queue = __pc_collections.deque([node])",
    "    while queue:",
    "        cur = queue.popleft()",
    "        if cur.val in by_val:",
    "            continue",
    "        by_val[cur.val] = cur",
    "        for neighbor in getattr(cur, 'neighbors', []) or []:",
    "            if neighbor.val not in by_val:",
    "                queue.append(neighbor)",
    "    if not by_val:",
    "        return []",
    "    size = max(by_val)",
    "    out = []",
    "    for value in range(1, size + 1):",
    "        cur = by_val.get(value)",
    "        out.append(sorted(neighbor.val for neighbor in (getattr(cur, 'neighbors', []) if cur else [])))",
    "    return out",
    "",
    "def __pc_quad_tree_to_list(root):",
    "    if root is None:",
    "        return []",
    "    out = []",
    "    queue = __pc_collections.deque([root])",
    "    while queue:",
    "        node = queue.popleft()",
    "        if node is None:",
    "            out.append(None)",
    "            continue",
    "        is_leaf = bool(getattr(node, 'isLeaf', False))",
    "        out.append([1 if is_leaf else 0, 1 if bool(getattr(node, 'val', False)) else 0])",
    "        if not is_leaf:",
    "            queue.append(getattr(node, 'topLeft', None))",
    "            queue.append(getattr(node, 'topRight', None))",
    "            queue.append(getattr(node, 'bottomLeft', None))",
    "            queue.append(getattr(node, 'bottomRight', None))",
    "    while out and out[-1] is None:",
    "        out.pop()",
    "    return out",
    "",
    "def __pc_list_to_cycle(values, pos):",
    "    head = __pc_list_to_linked(values)",
    "    if head is None or not isinstance(pos, int) or pos < 0:",
    "        return head",
    "    nodes = []",
    "    cur = head",
    "    while cur is not None:",
    "        nodes.append(cur)",
    "        if cur.next is None:",
    "            break",
    "        cur = cur.next",
    "    if 0 <= pos < len(nodes):",
    "        nodes[-1].next = nodes[pos]",
    "    return head",
    "",
    "def __pc_deserialize(value, type_name):",
    "    normalized = __pc_normalize_type(type_name)",
    "    adapter = __pc_contract.get('inputAdapter')",
    "    if adapter == 'node_random_list':",
    "        return __pc_list_to_random_node(value)",
    "    if adapter == 'node_graph':",
    "        return __pc_list_to_graph(value)",
    "    if adapter == 'node_next_tree':",
    "        return __pc_list_to_node_tree(value)",
    "    if 'listnode' in normalized and (normalized.startswith('list<') or normalized.endswith('[]')):",
    "        return [__pc_list_to_linked(item) if item is not None else None for item in (value or [])]",
    "    if 'listnode' in normalized:",
    "        return __pc_list_to_linked(value)",
    "    if 'treenode' in normalized:",
    "        return __pc_list_to_tree(value)",
    "    return value",
    "",
    "def __pc_serialize(value, type_name=None):",
    "    normalized = __pc_normalize_type(type_name)",
    "    adapter = __pc_contract.get('inputAdapter')",
    "    if value is None:",
    "        return None",
    "    if adapter == 'node_random_list':",
    "        return __pc_random_node_to_list(value)",
    "    if adapter == 'node_graph':",
    "        return __pc_graph_to_list(value)",
    "    if adapter == 'node_next_tree':",
    "        return __pc_node_next_to_list(value)",
    "    if adapter == 'quad_tree':",
    "        return __pc_quad_tree_to_list(value)",
    "    if isinstance(value, ListNode) or 'listnode' in normalized:",
    "        return __pc_linked_to_list(value)",
    "    if isinstance(value, TreeNode) or 'treenode' in normalized:",
    "        return __pc_tree_to_list(value)",
    "    if isinstance(value, tuple):",
    "        return [__pc_serialize(item) for item in value]",
    "    if isinstance(value, list):",
    "        return [__pc_serialize(item) for item in value]",
    "    if isinstance(value, dict):",
    "        return {str(key): __pc_serialize(entry) for key, entry in value.items()}",
    "    return value",
    "",
    "def __pc_sortable(value):",
    "    if isinstance(value, list):",
    "        return sorted((__pc_sortable(item) for item in value), key=lambda item: __pc_json.dumps(item, sort_keys=True))",
    "    if isinstance(value, dict):",
    "        return {key: __pc_sortable(value[key]) for key in sorted(value)}",
    "    return value",
    "",
    "def __pc_sort_key(value):",
    "    return __pc_json.dumps(value, sort_keys=True, separators=(',', ':'))",
    "",
    "def __pc_equal_float(actual, expected, eps):",
    "    if isinstance(actual, (int, float)) and isinstance(expected, (int, float)):",
    "        return __pc_math.isclose(float(actual), float(expected), rel_tol=eps, abs_tol=eps)",
    "    if isinstance(actual, list) and isinstance(expected, list):",
    "        return len(actual) == len(expected) and all(__pc_equal_float(a, e, eps) for a, e in zip(actual, expected))",
    "    if isinstance(actual, dict) and isinstance(expected, dict):",
    "        return set(actual.keys()) == set(expected.keys()) and all(__pc_equal_float(actual[key], expected[key], eps) for key in actual)",
    "    return actual == expected",
    "",
    "def __pc_equal_op_sequence(actual, expected, test):",
    "    if not isinstance(actual, list) or not isinstance(expected, list) or len(actual) != len(expected):",
    "        return False",
    "    operations = ((test or {}).get('input') or {}).get('operations') or []",
    "    ignored = set(__pc_comparison_config.get('ignoreOps') or [])",
    "    eps = float(__pc_comparison_config.get('epsilon', 1e-6))",
    "    for index, (actual_item, expected_item) in enumerate(zip(actual, expected)):",
    "        operation = operations[index] if index < len(operations) else None",
    "        if operation in ignored or expected_item is None:",
    "            continue",
    "        if not __pc_equal_float(actual_item, expected_item, eps):",
    "            return False",
    "    return True",
    "",
    "def __pc_equal_special(actual, expected, test):",
    "    if __pc_comparison_config.get('kind') == 'topological_order':",
    "        input_value = (test or {}).get('input') or {}",
    "        num_courses = input_value.get(__pc_comparison_config.get('numCoursesParam', 'numCourses'))",
    "        prerequisites = input_value.get(__pc_comparison_config.get('prerequisitesParam', 'prerequisites')) or []",
    "        if expected == []:",
    "            return actual == []",
    "        if not isinstance(num_courses, int) or not isinstance(actual, list) or len(actual) != num_courses:",
    "            return False",
    "        if sorted(actual) != list(range(num_courses)):",
    "            return False",
    "        position = {course: index for index, course in enumerate(actual)}",
    "        for pair in prerequisites:",
    "            if not isinstance(pair, list) or len(pair) != 2:",
    "                return False",
    "            course, before = pair",
    "            if position.get(before, -1) > position.get(course, -1):",
    "                return False",
    "        return True",
    "    return actual == expected",
    "",
    "def __pc_equal(actual, expected, test=None):",
    "    strategy = __pc_comparison_strategy",
    "    if strategy == 'unordered':",
    "        return __pc_sortable(actual) == __pc_sortable(expected)",
    "    if strategy == 'multiset_top':",
    "        if not isinstance(actual, list) or not isinstance(expected, list):",
    "            return actual == expected",
    "        return sorted(actual, key=__pc_sort_key) == sorted(expected, key=__pc_sort_key)",
    "    if strategy == 'multiset_deep':",
    "        return __pc_sortable(actual) == __pc_sortable(expected)",
    "    if strategy == 'float_tol':",
    "        eps = float(__pc_comparison_config.get('epsilon', 1e-6))",
    "        return __pc_equal_float(actual, expected, eps)",
    "    if strategy == 'op_sequence':",
    "        return __pc_equal_op_sequence(actual, expected, test)",
    "    if strategy == 'special_judge':",
    "        return __pc_equal_special(actual, expected, test)",
    "    return actual == expected",
    "",
    "def __pc_emit(payload):",
    "    print(__pc_marker + __pc_json.dumps(payload, ensure_ascii=False, separators=(',', ':')))",
    "",
    "def __pc_stream_text(stream):",
    "    value = stream.getvalue()",
    "    return value[:-1] if value.endswith('\\n') else value",
    "",
    "def __pc_method_owner():",
    "    class_name = __pc_contract.get('name')",
    "    if __pc_contract.get('contractKind') == 'design_class' and class_name in globals():",
    "        return globals()[class_name]",
    "    return Solution()",
    "",
    "def __pc_design_arg_type(class_name, operation, index):",
    "    if class_name == 'BSTIterator' and operation == class_name and index == 0:",
    "        return 'TreeNode'",
    "    return 'unknown'",
    "",
    "def __pc_design_args(class_name, operation, args):",
    "    return [__pc_deserialize(__pc_copy.deepcopy(value), __pc_design_arg_type(class_name, operation, index)) for index, value in enumerate(args or [])]",
    "",
    "def __pc_run_design(test):",
    "    operations = test.get('input', {}).get('operations')",
    "    arguments = test.get('input', {}).get('arguments')",
    "    if not isinstance(operations, list) or not isinstance(arguments, list) or not operations:",
    "        raise TypeError('design-class tests need operations and arguments arrays')",
    "    klass = globals().get(operations[0])",
    "    if klass is None:",
    "        raise NameError(f'design class {operations[0]} is not defined')",
    "    instance = klass(*__pc_design_args(operations[0], operations[0], arguments[0]))",
    "    outputs = [None]",
    "    for op, op_args in zip(operations[1:], arguments[1:]):",
    "        outputs.append(__pc_serialize(getattr(instance, op)(*__pc_design_args(operations[0], op, op_args))))",
    "    return outputs",
    "",
    "def __pc_run_case(test):",
    "    if __pc_contract.get('contractKind') == 'design_class':",
    "        return __pc_run_design(test)",
    "    input_value = test.get('input', {})",
    "    if not isinstance(input_value, dict):",
    "        raise TypeError('test input must be a JSON object keyed by LeetCode parameter name')",
    "    if __pc_contract.get('inputAdapter') == 'linked_list_with_cycle':",
    "        owner = __pc_method_owner()",
    "        method = getattr(owner, __pc_contract.get('name'))",
    "        return __pc_serialize(method(__pc_list_to_cycle(__pc_copy.deepcopy(input_value.get('head')), input_value.get('pos'))), __pc_contract.get('returnType'))",
    "    owner = __pc_method_owner()",
    "    method = getattr(owner, __pc_contract.get('name'))",
    "    params = __pc_contract.get('params', [])",
    "    raw_args = []",
    "    runtime_args = []",
    "    for param in params:",
    "        name = param.get('name')",
    "        raw = input_value.get(name)",
    "        raw_args.append(raw)",
    "        runtime_args.append(__pc_deserialize(__pc_copy.deepcopy(raw), param.get('type')))",
    "    result = method(*runtime_args)",
    "    if __pc_contract.get('contractKind') == 'inplace_arg':",
    "        names = __pc_comparison_config.get('mutatedParamNames') or ([params[0].get('name')] if params else [])",
    "        mutated = {}",
    "        for name in names:",
    "            index = next((i for i, param in enumerate(params) if param.get('name') == name), -1)",
    "            if index >= 0:",
    "                mutated[name] = __pc_serialize(runtime_args[index], params[index].get('type'))",
    "        if len(mutated) == 1:",
    "            return next(iter(mutated.values()))",
    "        return mutated",
    "    return __pc_serialize(result, __pc_contract.get('returnType'))",
    "",
    "def __pc_run():",
    "    results = []",
    "    for test in __pc_tests:",
    "        __pc_stdout = __pc_io.StringIO()",
    "        __pc_stderr = __pc_io.StringIO()",
    "        try:",
    "            with __pc_contextlib.redirect_stdout(__pc_stdout), __pc_contextlib.redirect_stderr(__pc_stderr):",
    "                actual = __pc_run_case(test)",
    "            expected = test.get('expected')",
    "            passed = __pc_equal(actual, expected, test)",
    "            result = {",
    "                'id': test.get('id', ''),",
    "                'label': test.get('label', ''),",
    "                'input': test.get('input') if not passed else None,",
    "                'expected': expected if not passed else None,",
    "                'actual': actual if not passed else None,",
    "                'passed': passed,",
    "                'stdout': __pc_stream_text(__pc_stdout),",
    "                'stderr': __pc_stream_text(__pc_stderr),",
    "                'stdoutCaptured': True,",
    "                'stderrCaptured': True,",
    "            }",
    "            results.append(result)",
    "        except Exception as exc:",
    "            results.append({",
    "                'id': test.get('id', ''),",
    "                'label': test.get('label', ''),",
    "                'input': test.get('input'),",
    "                'expected': test.get('expected'),",
    "                'actual': None,",
    "                'passed': False,",
    "                'error': ''.join(__pc_traceback.format_exception_only(type(exc), exc)).strip(),",
    "                'errorLocation': __pc_traceback_error_location(exc),",
    "                'stdout': __pc_stream_text(__pc_stdout),",
    "                'stderr': __pc_stream_text(__pc_stderr),",
    "                'stdoutCaptured': True,",
    "                'stderrCaptured': True,",
    "            })",
    "            __pc_emit({'status': 'runtime_error', 'testResults': results, 'error': results[-1]['error'], 'errorLocation': results[-1].get('errorLocation')})",
    "            return",
    "    __pc_emit({'status': 'completed', 'testResults': results})",
  ].join("\n");
}
