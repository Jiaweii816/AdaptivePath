import type { DemoProblemAdapter } from "@/data/demo-problems";
import {
  cppStringLiteral,
  jsonForHarness,
} from "@/data/demo-problems/adapter.types";
import type { CodeRunTestCase } from "@/types/code-runner";
import { PISTON_RESULT_MARKER } from "./normalize-run-result";

export function buildCppWrapper(args: {
  adapter: DemoProblemAdapter;
  userCode: string;
  testCases: CodeRunTestCase[];
}) {
  const caseBlocks = args.testCases
    .map((testCase, index) =>
      buildCapturedCppCase({
        adapter: args.adapter,
        index,
        testCase,
      }),
    )
    .join("\n");

  return [
    "#include <algorithm>",
    "#include <exception>",
    "#include <iostream>",
    "#include <sstream>",
    "#include <streambuf>",
    "#include <string>",
    "#include <vector>",
    "using namespace std;",
    "",
    args.userCode,
    "",
    "static string __pc_escape_json_string(const string& value) {",
    "  string out;",
    "  for (char ch : value) {",
    "    switch (ch) {",
    "      case '\\\\': out += \"\\\\\\\\\"; break;",
    "      case '\"': out += \"\\\\\\\"\"; break;",
    "      case '\\n': out += \"\\\\n\"; break;",
    "      case '\\r': out += \"\\\\r\"; break;",
    "      case '\\t': out += \"\\\\t\"; break;",
    "      default: out += ch; break;",
    "    }",
    "  }",
    "  return out;",
    "}",
    "",
    "static string __pc_json_string(const string& value) {",
    "  return string(\"\\\"\") + __pc_escape_json_string(value) + \"\\\"\";",
    "}",
    "",
    "static string __pc_int_vector_json(vector<int> value) {",
    "  string out = \"[\";",
    "  for (size_t i = 0; i < value.size(); ++i) {",
    "    if (i > 0) out += \",\";",
    "    out += to_string(value[i]);",
    "  }",
    "  out += \"]\";",
    "  return out;",
    "}",
    "",
    "static bool __pc_equal_int_vector(vector<int> actual, vector<int> expected, bool order_matters) {",
    "  if (!order_matters) {",
    "    sort(actual.begin(), actual.end());",
    "    sort(expected.begin(), expected.end());",
    "  }",
    "  return actual == expected;",
    "}",
    "",
    "static string __pc_cases_json = \"[\";",
    "static bool __pc_first_case = true;",
    "static int __pc_passed_count = 0;",
    "static ostringstream __pc_case_stdout;",
    "static ostringstream __pc_case_stderr;",
    "static streambuf* __pc_saved_cout = nullptr;",
    "static streambuf* __pc_saved_cerr = nullptr;",
    "",
    "static string __pc_stream_text(string value) {",
    "  if (!value.empty() && value.back() == '\\n') value.pop_back();",
    "  if (!value.empty() && value.back() == '\\r') value.pop_back();",
    "  return value;",
    "}",
    "",
    "static void __pc_begin_case_capture() {",
    "  __pc_case_stdout.str(\"\");",
    "  __pc_case_stdout.clear();",
    "  __pc_case_stderr.str(\"\");",
    "  __pc_case_stderr.clear();",
    "  __pc_saved_cout = cout.rdbuf(__pc_case_stdout.rdbuf());",
    "  __pc_saved_cerr = cerr.rdbuf(__pc_case_stderr.rdbuf());",
    "}",
    "",
    "static void __pc_end_case_capture() {",
    "  if (__pc_saved_cout != nullptr) {",
    "    cout.rdbuf(__pc_saved_cout);",
    "    __pc_saved_cout = nullptr;",
    "  }",
    "  if (__pc_saved_cerr != nullptr) {",
    "    cerr.rdbuf(__pc_saved_cerr);",
    "    __pc_saved_cerr = nullptr;",
    "  }",
    "}",
    "",
    "static void __pc_add_case(const string& id, const string& label, const string& input_json, const string& expected_json, const string& actual_json, bool passed) {",
    "  if (!__pc_first_case) __pc_cases_json += \",\";",
    "  __pc_first_case = false;",
    "  if (passed) __pc_passed_count += 1;",
    "  __pc_cases_json += \"{\";",
    "  __pc_cases_json += \"\\\"id\\\":\" + __pc_json_string(id);",
    "  __pc_cases_json += \",\\\"label\\\":\" + __pc_json_string(label);",
    "  __pc_cases_json += \",\\\"input\\\":\" + input_json;",
    "  __pc_cases_json += \",\\\"expected\\\":\" + expected_json;",
    "  __pc_cases_json += \",\\\"actual\\\":\" + actual_json;",
    "  __pc_cases_json += \",\\\"passed\\\":\" + string(passed ? \"true\" : \"false\");",
    "  __pc_cases_json += \",\\\"stdout\\\":\" + __pc_json_string(__pc_stream_text(__pc_case_stdout.str()));",
    "  __pc_cases_json += \",\\\"stderr\\\":\" + __pc_json_string(__pc_stream_text(__pc_case_stderr.str()));",
    "  __pc_cases_json += \",\\\"stdoutCaptured\\\":true\";",
    "  __pc_cases_json += \",\\\"stderrCaptured\\\":true\";",
    "  __pc_cases_json += \"}\";",
    "}",
    "",
    "static void __pc_add_case_error(const string& id, const string& label, const string& input_json, const string& expected_json, const string& error) {",
    "  if (!__pc_first_case) __pc_cases_json += \",\";",
    "  __pc_first_case = false;",
    "  __pc_cases_json += \"{\";",
    "  __pc_cases_json += \"\\\"id\\\":\" + __pc_json_string(id);",
    "  __pc_cases_json += \",\\\"label\\\":\" + __pc_json_string(label);",
    "  __pc_cases_json += \",\\\"input\\\":\" + input_json;",
    "  __pc_cases_json += \",\\\"expected\\\":\" + expected_json;",
    "  __pc_cases_json += \",\\\"actual\\\":null\";",
    "  __pc_cases_json += \",\\\"passed\\\":false\";",
    "  __pc_cases_json += \",\\\"error\\\":\" + __pc_json_string(error);",
    "  __pc_cases_json += \",\\\"stdout\\\":\" + __pc_json_string(__pc_stream_text(__pc_case_stdout.str()));",
    "  __pc_cases_json += \",\\\"stderr\\\":\" + __pc_json_string(__pc_stream_text(__pc_case_stderr.str()));",
    "  __pc_cases_json += \",\\\"stdoutCaptured\\\":true\";",
    "  __pc_cases_json += \",\\\"stderrCaptured\\\":true\";",
    "  __pc_cases_json += \"}\";",
    "}",
    "",
    "static void __pc_emit(const string& status, const string& error = \"\") {",
    "  string payload = \"{\\\"status\\\":\" + __pc_json_string(status) + \",\\\"testResults\\\":\" + __pc_cases_json + \"]\";",
    "  if (!error.empty()) payload += \",\\\"error\\\":\" + __pc_json_string(error);",
    "  payload += \"}\";",
    `  cout << "${PISTON_RESULT_MARKER}" << payload << endl;`,
    "}",
    "",
    "int main() {",
    "  try {",
    caseBlocks,
    "  } catch (const exception& exc) {",
    "    __pc_emit(\"runtime_error\", exc.what());",
    "    return 0;",
    "  } catch (...) {",
    "    __pc_emit(\"runtime_error\", \"unknown C++ runtime error\");",
    "    return 0;",
    "  }",
    "  __pc_emit(\"completed\");",
    "  return 0;",
    "}",
    "",
  ].join("\n");
}

function buildCapturedCppCase(args: {
  adapter: DemoProblemAdapter;
  index: number;
  testCase: CodeRunTestCase;
}) {
  const inputJson = cppStringLiteral(jsonForHarness(args.testCase.input));
  const expectedJson = cppStringLiteral(jsonForHarness(args.testCase.expected));
  const unknownError = "unknown C++ runtime error";

  return [
    "__pc_begin_case_capture();",
    "try {",
    args.adapter.buildCppCase(args.testCase, args.index),
    "  __pc_end_case_capture();",
    "} catch (const exception& exc) {",
    "  string __pc_error = exc.what();",
    "  __pc_end_case_capture();",
    "  __pc_add_case_error(",
    `    ${cppStringLiteral(args.testCase.id)},`,
    `    ${cppStringLiteral(args.testCase.label)},`,
    `    ${inputJson},`,
    `    ${expectedJson},`,
    "    __pc_error",
    "  );",
    "  __pc_emit(\"runtime_error\", __pc_error);",
    "  return 0;",
    "} catch (...) {",
    "  string __pc_error = " + cppStringLiteral(unknownError) + ";",
    "  __pc_end_case_capture();",
    "  __pc_add_case_error(",
    `    ${cppStringLiteral(args.testCase.id)},`,
    `    ${cppStringLiteral(args.testCase.label)},`,
    `    ${inputJson},`,
    `    ${expectedJson},`,
    "    __pc_error",
    "  );",
    "  __pc_emit(\"runtime_error\", __pc_error);",
    "  return 0;",
    "}",
  ].join("\n");
}
