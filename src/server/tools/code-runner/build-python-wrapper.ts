import type { DemoProblemAdapter } from "@/data/demo-problems";
import type { CodeRunTestCase } from "@/types/code-runner";
import { PISTON_RESULT_MARKER } from "./normalize-run-result";

export function buildPythonWrapper(args: {
  adapter: DemoProblemAdapter;
  userCode: string;
  testCases: CodeRunTestCase[];
}) {
  const testsJson = JSON.stringify(args.testCases);

  return [
    "from typing import *",
    "import contextlib as __pc_contextlib",
    "import io as __pc_io",
    "import json as __pc_json",
    "import traceback as __pc_traceback",
    "",
    `__pc_marker = ${JSON.stringify(PISTON_RESULT_MARKER)}`,
    `__pc_user_code_filename = "user_code.py"`,
    `__pc_user_code = ${JSON.stringify(args.userCode)}`,
    "",
    "def __pc_emit(payload):",
    "    print(__pc_marker + __pc_json.dumps(payload, ensure_ascii=False, separators=(',', ':')))",
    "",
    ...buildPythonUserCodeGuard(),
    "",
    "try:",
    "    __pc_compiled_user_code = compile(__pc_user_code, __pc_user_code_filename, 'exec')",
    "    exec(__pc_compiled_user_code, globals())",
    "except SyntaxError as exc:",
    "    __pc_error = __pc_format_error(exc)",
    "    __pc_emit({'status': 'syntax_error', 'testResults': [], 'error': __pc_error, 'errorLocation': __pc_syntax_error_location(exc)})",
    "    raise SystemExit(0)",
    "except Exception as exc:",
    "    __pc_error = __pc_format_error(exc)",
    "    __pc_emit({'status': 'runtime_error', 'testResults': [], 'error': __pc_error, 'errorLocation': __pc_traceback_error_location(exc)})",
    "    raise SystemExit(0)",
    "",
    `__pc_tests = __pc_json.loads(${JSON.stringify(testsJson)})`,
    `__pc_method_name = ${JSON.stringify(args.adapter.methodName)}`,
    `__pc_order_matters = ${args.adapter.orderMatters ? "True" : "False"}`,
    "",
    "def __pc_normalize(value):",
    "    if isinstance(value, tuple):",
    "        return list(value)",
    "    return value",
    "",
    "def __pc_equal(actual, expected):",
    "    actual = __pc_normalize(actual)",
    "    expected = __pc_normalize(expected)",
    "    if not __pc_order_matters and isinstance(actual, list) and isinstance(expected, list):",
    "        return sorted(actual) == sorted(expected)",
    "    return actual == expected",
    "",
    "def __pc_stream_text(stream):",
    "    value = stream.getvalue()",
    "    return value[:-1] if value.endswith('\\n') else value",
    "",
    "def __pc_run():",
    "    results = []",
    "    for test in __pc_tests:",
    "        __pc_stdout = __pc_io.StringIO()",
    "        __pc_stderr = __pc_io.StringIO()",
    "        try:",
    "            with __pc_contextlib.redirect_stdout(__pc_stdout), __pc_contextlib.redirect_stderr(__pc_stderr):",
    "                solution = Solution()",
    "                method = getattr(solution, __pc_method_name)",
    "                input_value = test.get('input', {})",
    "                if not isinstance(input_value, dict):",
    "                    raise TypeError('test input must be a JSON object')",
    "                actual = __pc_normalize(method(**input_value))",
    "            expected = __pc_normalize(test.get('expected'))",
    "            passed = __pc_equal(actual, expected)",
    "            results.append({",
    "                'id': test.get('id', ''),",
    "                'label': test.get('label', ''),",
    "                'input': input_value,",
    "                'expected': expected,",
    "                'actual': actual,",
    "                'passed': passed,",
    "                'stdout': __pc_stream_text(__pc_stdout),",
    "                'stderr': __pc_stream_text(__pc_stderr),",
    "                'stdoutCaptured': True,",
    "                'stderrCaptured': True,",
    "            })",
    "        except Exception as exc:",
    "            results.append({",
    "                'id': test.get('id', ''),",
    "                'label': test.get('label', ''),",
    "                'input': test.get('input'),",
    "                'expected': test.get('expected'),",
    "                'actual': None,",
    "                'passed': False,",
    "                'error': ''.join(__pc_traceback.format_exception_only(type(exc), exc)).strip(),",
    "                'errorLocation': __pc_traceback_error_location(exc),",
    "                'stdout': __pc_stream_text(__pc_stdout),",
    "                'stderr': __pc_stream_text(__pc_stderr),",
    "                'stdoutCaptured': True,",
    "                'stderrCaptured': True,",
    "            })",
    "            __pc_emit({'status': 'runtime_error', 'testResults': results, 'error': results[-1]['error'], 'errorLocation': results[-1].get('errorLocation')})",
    "            return",
    "    __pc_emit({'status': 'completed', 'testResults': results})",
    "",
    "__pc_run()",
    "",
  ].join("\n");
}

export function buildPythonUserCodeGuard() {
  return [
    "def __pc_format_error(exc):",
    "    return ''.join(__pc_traceback.format_exception_only(type(exc), exc)).strip()",
    "",
    "def __pc_positive_int(value):",
    "    try:",
    "        parsed = int(value)",
    "    except Exception:",
    "        return None",
    "    return parsed if parsed > 0 else None",
    "",
    "def __pc_finish_error_location(location, message):",
    "    if not location or not location.get('line'):",
    "        return None",
    "    if message:",
    "        location['message'] = message",
    "    return location",
    "",
    "def __pc_syntax_error_location(exc):",
    "    location = {}",
    "    line = __pc_positive_int(getattr(exc, 'lineno', None))",
    "    column = __pc_positive_int(getattr(exc, 'offset', None))",
    "    end_line = __pc_positive_int(getattr(exc, 'end_lineno', None))",
    "    end_column = __pc_positive_int(getattr(exc, 'end_offset', None))",
    "    if line is not None:",
    "        location['line'] = line",
    "    if column is not None:",
    "        location['column'] = column",
    "    if end_line is not None:",
    "        location['endLine'] = end_line",
    "    if end_column is not None:",
    "        location['endColumn'] = end_column",
    "    return __pc_finish_error_location(location, __pc_format_error(exc))",
    "",
    "def __pc_traceback_error_location(exc):",
    "    location = None",
    "    for frame in __pc_traceback.extract_tb(exc.__traceback__):",
    "        if frame.filename != __pc_user_code_filename:",
    "            continue",
    "        line = __pc_positive_int(getattr(frame, 'lineno', None))",
    "        if line is None:",
    "            continue",
    "        location = {'line': line}",
    "        column = __pc_positive_int(getattr(frame, 'colno', None))",
    "        end_line = __pc_positive_int(getattr(frame, 'end_lineno', None))",
    "        end_column = __pc_positive_int(getattr(frame, 'end_colno', None))",
    "        if column is not None:",
    "            location['column'] = column",
    "        if end_line is not None:",
    "            location['endLine'] = end_line",
    "        if end_column is not None:",
    "            location['endColumn'] = end_column",
    "    return __pc_finish_error_location(location, __pc_format_error(exc))",
  ];
}
